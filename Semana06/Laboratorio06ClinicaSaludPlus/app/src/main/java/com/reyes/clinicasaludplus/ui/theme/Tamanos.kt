package com.reyes.clinicasaludplus.ui.theme

import androidx.compose.ui.unit.sp

/**
 * Escala única de tamaños de texto de la app. Todas las pantallas usan estos valores,
 * de modo que el mismo tipo de texto se ve igual en cada sección.
 */
object Tam {
    val Titulo = 24.sp     // Título principal dentro de una pantalla
    val Barra = 20.sp      // Título de la barra superior y de los diálogos
    val Subtitulo = 18.sp  // Nombres, títulos de sección y botones principales
    val Cuerpo = 16.sp     // Texto normal, campos de formulario y botones secundarios
    val Pequeno = 14.sp    // Detalles, etiquetas, chips y mensajes de error
}
