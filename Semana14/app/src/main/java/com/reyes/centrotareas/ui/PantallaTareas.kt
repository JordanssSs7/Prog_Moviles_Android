@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PantallaTareas(vm: TareasViewModel) {
    val mensaje by vm.mensaje.collectAsState()
    // Prueba de vida: si deja de sumar, la pantalla está congelada
    var toques by rememberSaveable { mutableIntStateOf(0) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("CentroTareas", fontWeight = FontWeight.Bold) },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primary,
                    titleContentColor = MaterialTheme.colorScheme.onPrimary
                )
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .padding(padding)
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            // ----- Tarea con progreso (pasos 1 a 4)
            Tarjeta {
                Button(onClick = { toques++ }) { Text("Tócame: $toques") }
                Button(onClick = { vm.tareaLargaMala() }) { Text("Tarea larga (MAL)") }
                // TODO Paso 3: barra de progreso y porcentaje
                // TODO Paso 4: botones Iniciar y Cancelar
                Text(
                    text = mensaje,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    style = MaterialTheme.typography.bodyMedium
                )
            }

            // TODO Paso 5: tarjeta Contar números primos

            // TODO Paso 6 y 7: tarjeta Dos cargas
        }
    }
}
